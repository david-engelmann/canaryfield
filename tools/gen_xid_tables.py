#!/usr/bin/env python3
"""Generate src/xid_tables.rs, the identifier tables of
the port's tokenizer.

The interpreter reads an identifier through its XID
tables, a name starting with an XID_Start character and
continuing with XID_Continue characters. This script
reads the tables out of the running interpreter itself,
membership stated by str.isidentifier over one character
for the start table and over a character standing after
a letter for the continue table, and writes the ranges
as Rust data. Run it with the interpreter the port is
judged against and no other.

Usage: gen_xid_tables.py OUTPUT
"""

import sys
import unicodedata


def ranges(predicate):
    found = []
    start = None
    previous = None
    for codepoint in range(0x110000):
        if predicate(chr(codepoint)):
            if start is None:
                start = codepoint
            previous = codepoint
        elif start is not None:
            found.append((start, previous))
            start = None
    if start is not None:
        found.append((start, previous))
    return found


def spell(name, table):
    lines = [f"pub const {name}: &[(u32, u32)] = &["]
    for low, high in table:
        lines.append(f"    (0x{low:x}, 0x{high:x}),")
    lines.append("];")
    return lines


def main():
    start = ranges(lambda ch: ch.isidentifier())
    cont = ranges(lambda ch: ("x" + ch).isidentifier())
    out = [
        "//! The identifier tables of the tokenizer's reading,",
        "//! generated by tools/gen_xid_tables.py from the",
        f"//! interpreter's own tables, Unicode {unicodedata.unidata_version}.",
        "//! A name starts with an XID_Start character and",
        "//! continues with XID_Continue characters, the two",
        "//! readings the interpreter makes of a name.",
        "",
    ]
    out += spell("XID_START", start)
    out.append("")
    out += spell("XID_CONTINUE", cont)
    out.append("")
    with open(sys.argv[1], "w", encoding="utf-8") as handle:
        handle.write("\n".join(out))
    print(f"start ranges {len(start)}, continue ranges {len(cont)}")


if __name__ == "__main__":
    main()
